// Generates src/styles/tokens.css: perceptually even 50–950 scales in OKLCH,
// anchored on the four core colours of the brief (§6.2). Run: node scripts/tokens.mjs
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { hexToRgb, oklchToRgb, rgbToHex, rgbToOklch } from "./color.mjs";

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

// [lightness, chroma] per step. Hue comes from the family's core colour.
// Exact hex anchors from the brief override the generated step.
const FAMILIES = {
  navy: {
    hue: 259.9,
    lc: [[0.97, 0.012], [0.93, 0.022], [0.86, 0.036], [0.76, 0.056], [0.64, 0.074], [0.52, 0.084], [0.388, 0.082], [0.335, 0.076], [0.283, 0.066], [0.24, 0.054], [0.2, 0.04]],
    anchors: { 600: "#2A4470", 800: "#15294A", 950: "#0B1628" },
  },
  parchment: {
    hue: 87.5,
    lc: [[0.98, 0.01], [0.95, 0.021], [0.92, 0.028], [0.888, 0.035], [0.82, 0.036], [0.74, 0.034], [0.64, 0.03], [0.54, 0.026], [0.44, 0.022], [0.34, 0.018], [0.26, 0.014]],
    anchors: { 50: "#FBF8F1", 100: "#F4EEDF", 300: "#E4D9C0" },
  },
  gold: {
    hue: 80.4,
    lc: [[0.97, 0.02], [0.94, 0.04], [0.89, 0.068], [0.83, 0.09], [0.77, 0.102], [0.71, 0.107], [0.62, 0.1], [0.51, 0.085], [0.43, 0.07], [0.35, 0.055], [0.27, 0.04]],
    // 500 is Seal Gold. 700 is darkened from the brief's #8A6A2F (4.34:1 on
    // parchment, fails AA) so gold text passes; see docs/design/contrast.md.
    anchors: { 500: "#C49A4E" },
  },
  green: {
    hue: 161.1,
    lc: [[0.97, 0.016], [0.93, 0.03], [0.86, 0.05], [0.77, 0.068], [0.67, 0.08], [0.57, 0.084], [0.479, 0.078], [0.41, 0.068], [0.35, 0.058], [0.29, 0.046], [0.22, 0.034]],
    anchors: { 600: "#2F6B4F" },
  },
  ink: {
    hue: 262,
    lc: [[0.97, 0.004], [0.92, 0.008], [0.84, 0.012], [0.74, 0.016], [0.63, 0.022], [0.53, 0.027], [0.438, 0.03], [0.37, 0.028], [0.3, 0.026], [0.217, 0.022], [0.16, 0.018]],
    anchors: { 600: "#4A5263", 900: "#141A24" },
  },
};

export function buildScales() {
  const out = {};
  for (const [name, fam] of Object.entries(FAMILIES)) {
    STEPS.forEach((step, i) => {
      const anchor = fam.anchors[step];
      const [l, c] = fam.lc[i];
      const hex = anchor ?? rgbToHex(oklchToRgb([l, c, fam.hue]));
      const [L, C, H] = rgbToOklch(hexToRgb(hex));
      out[`${name}-${step}`] = { hex, css: `oklch(${(L * 100).toFixed(1)}% ${C.toFixed(3)} ${H.toFixed(1)})` };
    });
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const scales = buildScales();
  const lines = Object.entries(scales).map(([k, v]) => `  --${k}: ${v.css}; /* ${v.hex} */`);
  const css = `/* Generated by scripts/tokens.mjs — do not edit by hand. */
:root {
${lines.join("\n")}

  /* Core colours (brief §6.2) */
  --covenant-navy: #15294a;
  --ledger-parchment: #f4eedf;
  --seal-gold: #c49a4e;
  --laurel-green: #2f6b4f;
}
`;
  const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "styles", "tokens.css");
  writeFileSync(target, css);
  console.log(`wrote ${Object.keys(scales).length} tokens to ${target}`);
}
