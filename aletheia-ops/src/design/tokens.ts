/** The CSS custom properties, as written to tokens.css. */
export function toCss(): string {
  const lines: string[] = ["/* Generated by scripts/build-tokens.mts from src/design/tokens.ts. Do not edit. */", ":root {"];
  for (const [k, v] of Object.entries(palette)) lines.push(`  --p-${k}: ${v};`);
  for (const [k, v] of Object.entries(color)) lines.push(`  --c-${k}: ${v};`);
  for (const [k, [size, lh, weight, track]] of Object.entries(type)) {
    lines.push(`  --t-${k}-size: ${size / 16}rem;`);
    lines.push(`  --t-${k}-lh: ${lh / 16}rem;`);
    lines.push(`  --t-${k}-weight: ${weight};`);
    lines.push(`  --t-${k}-track: ${track}em;`);
  }
  for (const [k, v] of Object.entries(radius)) lines.push(`  --r-${k}: ${v}px;`);
  lines.push(`  --dur-quick: ${motion.quick}ms;`, `  --dur-base: ${motion.base}ms;`, `  --dur-panel: ${motion.panel}ms;`);
  lines.push(`  --ease-out: ${motion.ease};`, `  --ease-standard: ${motion.standard};`);
  lines.push(`  --shadow-pop: ${shadow.pop};`);
  for (const [k, v] of Object.entries(layout)) lines.push(`  --l-${k}: ${v}px;`);
  lines.push("}", "");

  // Tailwind theme: only these names exist as utilities, so nothing outside the scale can be used.
  lines.push("@theme inline {", "  --color-*: initial;", "  --color-transparent: transparent;", "  --color-current: currentColor;");
  for (const k of Object.keys(color)) lines.push(`  --color-${k}: var(--c-${k});`);
  lines.push("  --text-*: initial;");
  for (const k of Object.keys(type)) {
    lines.push(`  --text-${k}: var(--t-${k}-size);`);
    lines.push(`  --text-${k}--line-height: var(--t-${k}-lh);`);
    lines.push(`  --text-${k}--font-weight: var(--t-${k}-weight);`);
    lines.push(`  --text-${k}--letter-spacing: var(--t-${k}-track);`);
  }
  lines.push("  --radius-*: initial;");
  for (const k of Object.keys(radius)) lines.push(`  --radius-${k}: var(--r-${k});`);
  lines.push("  --shadow-*: initial;", "  --shadow-pop: var(--shadow-pop);");
  lines.push("  --spacing: 0.25rem;");
  lines.push("  --font-sans: var(--font-manrope), ui-sans-serif, system-ui, sans-serif;");
  lines.push("  --ease-out: var(--ease-out);", "  --ease-standard: var(--ease-standard);");
  lines.push("  --breakpoint-*: initial;");
  for (const [k, px] of Object.entries(breakpoints)) lines.push(`  --breakpoint-${k}: ${px / 16}rem;`);
  lines.push("}", "");
  return lines.join("\n");
}

/** Brief §14: 375 (base), 768, 1024, 1280, 1600. */
